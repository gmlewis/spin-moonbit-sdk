// -*- compile-command: "cd ../../wit && ./run-wit-bindgen.sh"; -*-

// wit-translate runs `wit-bindgen moonbit` and then translates its output into
// the "beautiful" Spin SDK structure that this repository has always used.
//
// wit-bindgen's MoonBit backend emits:
//
//	moon.mod.json
//	gen/{ffi.mbt,moon.pkg.json}
//	gen/interface/<ns>/<pkg>/<iface>/{top.mbt,ffi.mbt,moon.pkg.json}   (world exports)
//	interface/<ns>/<pkg>/<iface>/{top.mbt,ffi.mbt,moon.pkg.json,README.md}
//	world/<world>/{import.mbt,ffi_import.mbt,moon.pkg.json}
//
// with private `mbt_ffi_*` primitives duplicated into every generated package,
// kebab-case directory names, and the deprecated JSON manifest files.
//
// This program turns that into:
//
//	ffi/top_wasm.mbt            (hoisted, deduplicated, `pub` FFI primitives)
//	gen/{moon.pkg,ffi.mbt}      (thin `cabi_realloc` wrapper + link options)
//	interface/<ns>/<pkg>/<iface>/{moon.pkg,top.mbt,ffi.mbt,README.md}
//
// Exactly like the original layout: one shared `@ffi` package, camelCase
// interface directories, `moon.pkg` rather than `moon.pkg.json`, no `world/`
// directory, and no generated export trampoline (the application supplies
// `cabi_realloc` + `wasmExportHandle` itself).
//
// It must be run from the `wit/` directory (or via wit/run-wit-bindgen.sh),
// with `wit-bindgen` (>= 0.62.0) and `moon` in $PATH.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

const (
	// moduleName is the MoonBit module name of this SDK; it is what
	// wit-bindgen uses to build the import paths in the generated code.
	moduleName = "gmlewis/spin-moonbit-sdk"

	// ffiImport is the shared FFI helper package every generated package uses.
	ffiImport = moduleName + "/ffi"

	// genDir is the wit-bindgen "program entrance" directory.
	genDir = "gen"
)

var (
	itemSepRE = regexp.MustCompile(`(?m)^///\|\s*$`)

	// generatedHeaderRE matches wit-bindgen's "DO NOT EDIT" banner.
	generatedHeaderRE = regexp.MustCompile("(?m)^// Generated by `wit-bindgen` ([0-9][^ ]*)\\. DO NOT EDIT!")

	// mbtFFIDefRE matches a definition of one of wit-bindgen's private FFI shims.
	mbtFFIDefRE = regexp.MustCompile(`(?m)^(?:#\w+\([^)]*\)\n)?(?:pub\s+)?(?:extern "wasm"\s+)?fn (mbt_ffi_[A-Za-z0-9_]+)`)

	// mbtFFIRefRE matches any reference to one of them.
	mbtFFIRefRE = regexp.MustCompile(`mbt_ffi_[A-Za-z0-9_]+`)

	// quotedPathRE matches an import path inside a moon.pkg file.
	quotedPathRE = regexp.MustCompile(`"[^"\n]*/[^"\n]*"`)

	// importBlockStartRE matches the opening of an import block.
	importBlockStartRE = regexp.MustCompile(`(?m)^import \{\n`)
)

// ffiOrder is the order in which the hoisted FFI primitives are written to
// ffi/top_wasm.mbt. Anything not listed is appended alphabetically.
var ffiOrder = []string{
	"extend8",
	"extend16",
	"store8",
	"load8_u",
	"load8",
	"store16",
	"load16",
	"load16_u",
	"store32",
	"load32",
	"store64",
	"load64",
	"storef32",
	"loadf32",
	"storef64",
	"loadf64",
	"malloc",
	"free",
	"copy",
	"str2ptr",
	"ptr2str",
	"bytes2ptr",
	"ptr2bytes",
	"uint_array2ptr",
	"uint64_array2ptr",
	"int_array2ptr",
	"int64_array2ptr",
	"float_array2ptr",
	"double_array2ptr",
	"ptr2uint_array",
	"ptr2uint64_array",
	"ptr2int_array",
	"ptr2int64_array",
	"ptr2float_array",
	"ptr2double_array",
	"cabi_realloc",
}

type ffiDef struct {
	name     string // without the mbt_ffi_ prefix
	full     string // with the mbt_ffi_ prefix
	body     string // full item text, no leading "///|"
	fromFile string
}

type renamer struct {
	// old base name -> new (camelCase) base name
	dirs map[string]string
}

func main() {
	log.SetFlags(0)

	var (
		witPath  = flag.String("wit", ".", "path to the WIT directory handed to wit-bindgen")
		repoRoot = flag.String("repo", "..", "path to the SDK repository root")
		wb       = flag.String("wit-bindgen", envOr("WIT_BINDGEN", "wit-bindgen"), "wit-bindgen executable")
		derive   = flag.String("derive", "debug,eq", "comma-separated `--derive-*` options; use `show,eq` to reproduce the pre-0.62 output")
		keep     = flag.Bool("keep", false, "keep the temporary wit-bindgen output directory")
		dryRun   = flag.Bool("n", false, "translate but do not install into the repository")
	)
	flag.Parse()

	absWit, err := filepath.Abs(*witPath)
	must(err)
	absRepo, err := filepath.Abs(*repoRoot)
	must(err)

	if !fileExists(filepath.Join(absRepo, "ffi", "moon.pkg")) {
		log.Fatalf("%v does not look like the Spin SDK repository root", absRepo)
	}

	tmp, err := os.MkdirTemp("", "wit-translate-")
	must(err)
	if !*keep && !*dryRun {
		defer os.RemoveAll(tmp)
	}
	log.Printf("Translating %v into %v (working dir %v)", absWit, absRepo, tmp)

	// 1. Generate the raw wit-bindgen output.
	args := []string{"moonbit", "--out-dir", tmp}
	for _, d := range strings.Split(*derive, ",") {
		if d = strings.TrimSpace(d); d != "" {
			args = append(args, "--derive-"+d)
		}
	}
	args = append(args, absWit)
	run("", *wb, args...)

	// 2. Let `moon fmt` do two jobs at once: migrate the deprecated
	// moon.mod.json/moon.pkg.json manifests to moon.mod/moon.pkg, and format
	// the generated MoonBit source (wit-bindgen emits unformatted code).
	run(tmp, "moon", "fmt")
	os.RemoveAll(filepath.Join(tmp, "_build"))

	// 3. Drop the generated module manifest: this repository owns its own.
	for _, f := range []string{"moon.mod", "moon.mod.json"} {
		os.Remove(filepath.Join(tmp, f))
	}

	// 4. Drop the world package: everything in it is already reachable through
	// the interface packages (the original script did `rm -rf world` too, but
	// fail loudly if upstream ever starts putting real code there).
	pruneWorld(tmp)

	// 5. Drop the generated export package -- the application supplies
	// `wasmExportHandle` itself (see examples/hello-world/external-exports.mbt).
	dropExportPackage(tmp)

	// 6. Rename kebab-case directories to this SDK's camelCase convention.
	ren := newRenamer()
	ren.renameDirs(tmp)
	ren.rewriteSources(tmp)

	// 7. Hoist the duplicated private FFI shims into one shared `ffi` package.
	ffiVersion, defs := hoistFFI(tmp)
	if ffiVersion == "" {
		log.Fatalf("could not determine the wit-bindgen version from the generated output")
	}
	writeFFIPackage(tmp, ffiVersion, defs)

	// 8. Write the `gen` package.
	writeGenPackage(tmp, ffiVersion)

	// 9. Drop the `warnings = "-44"` suppression wit-bindgen puts in every
	// package: after hoisting it is only needed where inline wasm remains,
	// i.e. the hand-written ffi package.
	dropUnneededWarnings(tmp)

	// 10. Give every package that now calls `@ffi.*` an import for it.
	addFFIImports(tmp)

	if *dryRun {
		log.Printf("Dry run: translated output left in %v", tmp)
		return
	}

	// 11. Install the translated tree into the repository.
	install(tmp, absRepo)

	// 12. Regenerate ffi/top_notwasm.mbt from ffi/top_wasm.mbt.
	run(absRepo, "go", "run", "cmd/gen-ffi-top-notwasm/main.go")

	// 13. Final formatting + interface files.
	run(absRepo, "moon", "fmt")
	run(absRepo, "moon", "info")
	log.Printf("Done.")
}

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

func run(dir string, name string, args ...string) {
	cmd := exec.Command(name, args...)
	if dir != "" {
		cmd.Dir = dir
	}
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("%v %v: %v", name, strings.Join(args, " "), err)
	}
}

// ---------------------------------------------------------------------------
// steps 4 & 5: prune generated packages this SDK does not want
// ---------------------------------------------------------------------------

func pruneWorld(tmp string) {
	worldDir := filepath.Join(tmp, "world")
	if !fileExists(worldDir) {
		return
	}
	var bad []string
	must(filepath.Walk(worldDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || !strings.HasSuffix(path, ".mbt") {
			return err
		}
		_, items := splitItems(readFile(path))
		for _, item := range items {
			var code []string
			for _, line := range strings.Split(item, "\n") {
				if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "///") {
					code = append(code, line)
				}
			}
			if len(code) > 0 {
				bad = append(bad, path)
			}
		}
		return nil
	}))
	if len(bad) > 0 {
		log.Fatalf("wit-bindgen now generates real code in world/: %v -- wit-translate must handle it", bad)
	}
	os.RemoveAll(worldDir)
}

// dropExportPackage removes the generated world-export trampolines and the
// import of them from gen/moon.pkg.
func dropExportPackage(tmp string) {
	exportDir := filepath.Join(tmp, genDir, "interface")
	if !fileExists(exportDir) {
		return
	}
	os.RemoveAll(exportDir)

	pkgPath := filepath.Join(tmp, genDir, "moon.pkg")
	src := readFile(pkgPath)
	src = removeImport(src, moduleName+"/"+genDir+"/")
	writeFile(pkgPath, src)
}

// removeImport drops every import entry whose path has the given prefix.
func removeImport(src, pathPrefix string) string {
	blk, ok := findImportBlock(src)
	if !ok {
		return src
	}
	var entries []string
	for _, line := range blk.entries {
		if p, _ := splitImportEntry(line); strings.HasPrefix(p, pathPrefix) {
			continue
		}
		entries = append(entries, line)
	}
	if len(entries) == 0 {
		return tidyPkg(joinBlocks(src[:blk.start], src[blk.end:]))
	}
	return tidyPkg(src[:blk.start] + renderImportBlock(entries) + src[blk.end:])
}

// ---------------------------------------------------------------------------
// step 6: kebab-case -> camelCase
// ---------------------------------------------------------------------------

func newRenamer() *renamer {
	return &renamer{dirs: map[string]string{}}
}

func (r *renamer) renameDirs(root string) {
	var dirs []string
	must(filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.IsDir() && path != root && strings.Contains(filepath.Base(path), "-") {
			dirs = append(dirs, path)
		}
		return nil
	}))
	// Deepest first so that renaming a parent never invalidates a child path.
	sort.Slice(dirs, func(i, j int) bool { return len(dirs[i]) > len(dirs[j]) })
	for _, dir := range dirs {
		base := filepath.Base(dir)
		newBase := kebabToCamel(base)
		if newBase == base {
			continue
		}
		newPath := filepath.Join(filepath.Dir(dir), newBase)
		if fileExists(newPath) {
			log.Fatalf("cannot rename %v to %v: destination exists", dir, newPath)
		}
		must(os.Rename(dir, newPath))
		r.dirs[base] = newBase
	}
	if len(r.dirs) > 0 {
		var pairs []string
		for k, v := range r.dirs {
			pairs = append(pairs, k+" -> "+v)
		}
		sort.Strings(pairs)
		log.Printf("Renamed %v directories: %v", len(pairs), strings.Join(pairs, ", "))
	}
}

func (r *renamer) rewriteSources(root string) {
	must(filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		switch {
		case strings.HasSuffix(path, ".mbt"):
			src := readFile(path)
			out := src
			for old, newBase := range r.dirs {
				out = strings.ReplaceAll(out, "@"+old+".", "@"+newBase+".")
			}
			if out != src {
				writeFile(path, out)
			}
		case filepath.Base(path) == "moon.pkg":
			src := readFile(path)
			out := quotedPathRE.ReplaceAllStringFunc(src, func(q string) string {
				parts := strings.Split(strings.Trim(q, `"`), "/")
				for i, p := range parts {
					if newBase, ok := r.dirs[p]; ok {
						parts[i] = newBase
					}
				}
				return `"` + strings.Join(parts, "/") + `"`
			})
			if out != src {
				writeFile(path, out)
			}
		}
		return nil
	}))
}

// kebabToCamel converts "wall-clock" to "wallClock".
func kebabToCamel(s string) string {
	if !strings.Contains(s, "-") {
		return s
	}
	parts := strings.Split(s, "-")
	var b strings.Builder
	b.WriteString(parts[0])
	for _, p := range parts[1:] {
		if p == "" {
			continue
		}
		rs := []rune(p)
		rs[0] = unicode.ToUpper(rs[0])
		b.WriteString(string(rs))
	}
	return b.String()
}

