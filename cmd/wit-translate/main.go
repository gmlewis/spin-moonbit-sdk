// hoistFFI removes every `mbt_ffi_*` definition from the generated tree,
// rewrites all remaining references to `@ffi.<name>`, and returns the union of
// the definitions along with the wit-bindgen version that produced them.
func hoistFFI(root string) (string, []ffiDef) {
	defs := map[string]ffiDef{}
	version := ""

	files := mbtFiles(root)

	// Pass 1: collect and remove every definition.
	for _, path := range files {
		src := readFile(path)
		if version == "" {
			if m := generatedHeaderRE.FindStringSubmatch(src); m != nil {
				version = m[1]
			}
		}
		header, items := splitItems(src)
		var kept []string
		for _, item := range items {
			m := mbtFFIDefRE.FindStringSubmatch(item)
			if m == nil {
				kept = append(kept, item)
				continue
			}
			full := m[1]
			name := strings.TrimPrefix(full, "mbt_ffi_")
			body := strings.TrimRight(item, "\n")
			if prev, ok := defs[name]; ok {
				if normalizeWS(prev.body) != normalizeWS(body) {
					log.Fatalf("conflicting definitions of %v:\n%v\nvs (%v):\n%v", full, prev.body, prev.fromFile, body)
				}
				continue
			}
			defs[name] = ffiDef{name: name, full: full, body: body, fromFile: path}
		}
		if out := rebuild(header, kept); out != src {
			writeFile(path, out)
		}
	}

	// Pass 2: now that every definition is known, rewrite the references.
	for _, path := range files {
		if !fileExists(path) {
			continue
		}
		src := readFile(path)
		out := mbtFFIRefRE.ReplaceAllStringFunc(src, func(ref string) string {
			name := strings.TrimPrefix(ref, "mbt_ffi_")
			if _, ok := defs[name]; !ok {
				log.Fatalf("%v references unknown FFI shim %v", path, ref)
			}
			return "@ffi." + name
		})
		if out != src {
			writeFile(path, out)
		}
	}

	list := make([]ffiDef, 0, len(defs))
	for _, d := range defs {
		list = append(list, d)
	}
	rank := map[string]int{}
	for i, n := range ffiOrder {
		rank[n] = i
	}
	unknown := map[string]bool{}
	sort.Slice(list, func(i, j int) bool { return rankOf(rank, list[i].name, unknown) < rankOf(rank, list[j].name, unknown) })
	var names []string
	for _, d := range list {
		names = append(names, d.name)
	}
	if len(unknown) > 0 {
		var ks []string
		for k := range unknown {
			ks = append(ks, k)
		}
		sort.Strings(ks)
		log.Printf("NOTE: new FFI primitives not in ffiOrder (please add them): %v", ks)
	}
	log.Printf("Hoisted %v FFI primitives from wit-bindgen %v: %v", len(list), version, strings.Join(names, " "))
	return version, list
}

func rankOf(rank map[string]int, name string, unknown map[string]bool) int {
	if r, ok := rank[name]; ok {
		return r
	}
	unknown[name] = true
	return len(ffiOrder)
}

func mbtFiles(root string) []string {
	var files []string
	must(filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(path, ".mbt") {
			files = append(files, path)
		}
		return nil
	}))
	sort.Strings(files)
	return files
}

// writeFFIPackage creates the shared ffi package from the hoisted definitions.
func writeFFIPackage(tmp, version string, defs []ffiDef) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by `wit-bindgen` %v. DO NOT EDIT!\n", version)
	for _, d := range defs {
		body := d.body
		// Rename the definition itself and make it public.
		switch {
		case strings.Contains(body, "pub fn "+d.full):
			body = strings.Replace(body, "pub fn "+d.full, "pub fn "+d.name, 1)
		case strings.Contains(body, "extern \"wasm\" fn "+d.full):
			body = strings.Replace(body, "extern \"wasm\" fn "+d.full, "pub extern \"wasm\" fn "+d.name, 1)
		case strings.Contains(body, "fn "+d.full):
			body = strings.Replace(body, "fn "+d.full, "pub fn "+d.name, 1)
		default:
			log.Fatalf("cannot find the declaration of %v in:\n%v", d.full, body)
		}
		// Rewrite the calls the bodies make to one another.
		body = mbtFFIRefRE.ReplaceAllStringFunc(body, func(ref string) string {
			return strings.TrimPrefix(ref, "mbt_ffi_")
		})
		b.WriteString("\n///|\n")
		b.WriteString(body)
		b.WriteString("\n")
	}

	dir := filepath.Join(tmp, "ffi")
	must(os.MkdirAll(dir, 0o755))
	writeFile(filepath.Join(dir, "top_wasm.mbt"), b.String())
}

