// step 9: drop the now-unnecessary warning suppression
// ---------------------------------------------------------------------------

// dropUnneededWarnings removes the `warnings = "-44"` (invalid inline wasm)
// suppression from every generated package that no longer contains inline wasm.
func dropUnneededWarnings(root string) {
	dropped := 0
	must(filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() || filepath.Base(path) != "moon.pkg" {
			return err
		}
		dir := filepath.Dir(path)
		entries, err := os.ReadDir(dir)
		must(err)
		for _, e := range entries {
			if !e.IsDir() && strings.HasSuffix(e.Name(), ".mbt") &&
				strings.Contains(readFile(filepath.Join(dir, e.Name())), "#|") {
				return nil
			}
		}
		src := readFile(path)
		var kept []string
		changed := false
		for _, line := range strings.Split(src, "\n") {
			if strings.HasPrefix(strings.TrimSpace(line), "warnings") {
				changed = true
				continue
			}
			kept = append(kept, line)
		}
		if changed {
			writeFile(path, tidyPkg(strings.Join(kept, "\n")))
			dropped++
		}
		return nil
	}))
	log.Printf("Dropped the now-unnecessary warning suppression from %v packages", dropped)
}

// ---------------------------------------------------------------------------
// step 10: add the @ffi import where it is needed
// ---------------------------------------------------------------------------

func addFFIImports(root string) {
	var dirs []string
	must(filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil || !info.IsDir() {
			return err
		}
		if fileExists(filepath.Join(path, "moon.pkg")) {
			dirs = append(dirs, path)
		}
		return nil
	}))
	sort.Strings(dirs)
	count := 0
	for _, dir := range dirs {
		entries, err := os.ReadDir(dir)
		must(err)
		need := false
		for _, e := range entries {
			if e.IsDir() || !strings.HasSuffix(e.Name(), ".mbt") {
				continue
			}
			if strings.Contains(readFile(filepath.Join(dir, e.Name())), "@ffi.") {
				need = true
				break
			}
		}
		if !need {
			continue
		}
		addImport(filepath.Join(dir, "moon.pkg"), ffiImport, "ffi")
		count++
	}
	log.Printf("Added the @ffi import to %v packages", count)
}

// addImport inserts `"path" @alias,` into the import block of a moon.pkg file,
// creating the block if necessary, and keeps the list sorted.
func addImport(pkgPath, path, alias string) {
	src := readFile(pkgPath)
	entry := fmt.Sprintf("%q @%v", path, alias)

	blk, ok := findImportBlock(src)
	if ok {
		for _, line := range blk.entries {
			if p, _ := splitImportEntry(line); p == path {
				return // already there
			}
		}
		entries := append(append([]string(nil), blk.entries...), entry)
		src = src[:blk.start] + renderImportBlock(entries) + src[blk.end:]
	} else {
		src = joinBlocks(renderImportBlock([]string{entry}), src)
	}
	writeFile(pkgPath, tidyPkg(src))
}

// joinBlocks joins non-empty sections with a single blank line between them.
func joinBlocks(parts ...string) string {
	var blocks []string
	for _, p := range parts {
		if p = strings.Trim(p, "\n"); strings.TrimSpace(p) != "" {
			blocks = append(blocks, p)
		}
	}
	return strings.Join(blocks, "\n\n")
}

// importBlock describes the `import { ... }` block of a moon.pkg file.
type importBlock struct {
	start   int // index of the leading "import {"
	end     int // index just past the closing "}"
	entries []string
}

// findImportBlock locates the import block of a moon.pkg file, if any.
func findImportBlock(src string) (importBlock, bool) {
	loc := importBlockStartRE.FindStringIndex(src)
	if loc == nil {
		return importBlock{}, false
	}
	bodyStart := loc[1]
	rest := src[bodyStart:]
	if strings.HasPrefix(rest, "}") {
		return importBlock{start: loc[0], end: bodyStart + 1}, true
	}
	idx := strings.Index(rest, "\n}")
	if idx < 0 {
		return importBlock{}, false
	}
	return importBlock{
		start:   loc[0],
		end:     bodyStart + idx + len("\n}"),
		entries: parseImportEntries(rest[:idx]),
	}, true
}

// parseImportEntries returns the trimmed entries of an import block body.
func parseImportEntries(body string) []string {
	var entries []string
	for _, line := range strings.Split(body, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		entries = append(entries, strings.TrimSuffix(line, ","))
	}
	return entries
}

// splitImportEntry splits `"path" @alias` into its path and alias.
func splitImportEntry(entry string) (string, string) {
	path := entry
	alias := ""
	if i := strings.Index(entry, `"`); i == 0 {
		if j := strings.Index(entry[1:], `"`); j >= 0 {
			path = entry[1 : 1+j]
			rest := strings.TrimSpace(entry[2+j:])
			alias = strings.TrimPrefix(rest, "@")
		}
	}
	return path, alias
}

// renderImportBlock writes a sorted import block (without a trailing newline).
func renderImportBlock(entries []string) string {
	sorted := append([]string(nil), entries...)
	sort.Slice(sorted, func(i, j int) bool {
		pi, ai := splitImportEntry(sorted[i])
		pj, aj := splitImportEntry(sorted[j])
		if pi != pj {
			return pi < pj
		}
		return ai < aj
	})
	var b strings.Builder
	b.WriteString("import {\n")
	for _, e := range sorted {
		b.WriteString("  " + e + ",\n")
	}
	b.WriteString("}")
	return b.String()
}

