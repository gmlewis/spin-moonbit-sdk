// splitItems splits a MoonBit file into its header (everything before the first
// "///|" separator) and its top-level items.
func splitItems(src string) (string, []string) {
	locs := itemSepRE.FindAllStringIndex(src, -1)
	if len(locs) == 0 {
		return src, nil
	}
	header := src[:locs[0][0]]
	var items []string
	for i, loc := range locs {
		start := loc[1]
		end := len(src)
		if i+1 < len(locs) {
			end = locs[i+1][0]
		}
		if item := strings.Trim(src[start:end], "\n"); item != "" {
			items = append(items, item)
		}
	}
	return header, items
}

func rebuild(header string, items []string) string {
	var b strings.Builder
	b.WriteString(strings.TrimRight(header, "\n"))
	b.WriteString("\n")
	for _, item := range items {
		b.WriteString("\n///|\n")
		b.WriteString(strings.TrimRight(item, "\n"))
		b.WriteString("\n")
	}
	return b.String()
}

var wsRE = regexp.MustCompile(`\s+`)

func normalizeWS(s string) string {
	return strings.TrimSpace(wsRE.ReplaceAllString(s, " "))
}

// tidyPkg normalises a moon.pkg file: blocks of non-blank lines separated by a
// single blank line, no leading or trailing blank lines, one trailing newline.
func tidyPkg(src string) string {
	var blocks []string
	var cur []string
	flush := func() {
		if len(cur) > 0 {
			blocks = append(blocks, strings.Join(cur, "\n"))
			cur = nil
		}
	}
	for _, line := range strings.Split(src, "\n") {
		if strings.TrimSpace(line) == "" {
			flush()
			continue
		}
		cur = append(cur, strings.TrimRight(line, " \t"))
	}
	flush()
	if len(blocks) == 0 {
		return ""
	}
	return strings.Join(blocks, "\n\n") + "\n"
}

