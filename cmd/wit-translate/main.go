func install(tmp, repo string) {
	for _, name := range []string{"interface", genDir} {
		dst := filepath.Join(repo, name)
		os.RemoveAll(dst)
		must(copyTree(filepath.Join(tmp, name), dst))
	}
	must(copyTree(filepath.Join(tmp, "ffi", "top_wasm.mbt"), filepath.Join(repo, "ffi", "top_wasm.mbt")))
}

func copyTree(src, dst string) error {
	info, err := os.Stat(src)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		data, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, data, 0o644)
	}
	if err := os.MkdirAll(dst, 0o755); err != nil {
		return err
	}
	entries, err := os.ReadDir(src)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if err := copyTree(filepath.Join(src, e.Name()), filepath.Join(dst, e.Name())); err != nil {
			return err
		}
	}
	return nil
}

