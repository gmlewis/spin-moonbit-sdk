// genFFI is the thin program-entrance wrapper the application imports.
const genFFI = "// Generated by `wit-bindgen` %[1]v. DO NOT EDIT!\n" + `
///|
pub fn cabi_realloc(
  src_offset : Int,
  src_size : Int,
  _dst_alignment : Int,
  dst_size : Int,
) -> Int {
  @ffi.cabi_realloc(src_offset, src_size, _dst_alignment, dst_size)
}
`

// writeGenPackage replaces gen/ffi.mbt with the thin wrapper and fixes up the
// link configuration that wit-bindgen emitted.
func writeGenPackage(tmp, version string) {
	dir := filepath.Join(tmp, genDir)
	if !fileExists(dir) {
		log.Fatalf("%v was not generated", dir)
	}
	writeFile(filepath.Join(dir, "ffi.mbt"), fmt.Sprintf(genFFI, version))

	pkgPath := filepath.Join(dir, "moon.pkg")
	src := readFile(pkgPath)
	// `cabi_realloc` now lives in gen/ffi.mbt under its own name.
	src = strings.ReplaceAll(src, `"mbt_ffi_cabi_realloc:cabi_realloc"`, `"cabi_realloc:cabi_realloc"`)
	writeFile(pkgPath, src)
}

